package Day2Assignement;

public class Maxoftwo {
	
	
	public static void maxoftwo(int x, int y)
	{
		
			System.out.println("The maximum number is : " +Math.max(x, y));
		
	}
	
	public static void minimumoftwo(float x, float y)
	{
	
			System.out.println("The minimum number is : " +Math.min(x, y));
		
	}
	

	public static void main(String[] args)
	
	{
		maxoftwo(9,5);
		minimumoftwo(12.67f,15.89f);
		

	}

}
